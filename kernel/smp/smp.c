/* Configuration */
struct smp_config smp_config = {
    .max_cpus = MAX_CPUS,
    .apic_base = LAPIC_BASE_DEFAULT,
    .enabled = 1,
    .use_ioapic = 1,
    .use_lapic_timer = 1
};

/* AP trampoline code symbols from the binary (generated by objcopy) */
extern char _binary_build_arch_x86_64_ap_trampoline_bin_start[];
extern char _binary_build_arch_x86_64_ap_trampoline_bin_end[];

/* Kernel PML4 address - defined in vmm.c */
extern uint64_t kernel_pml4_phys;

/* AP bootstrap state */
static volatile int ap_boot_phase = SMP_PHASE_NONE;
static volatile uint32_t ap_booted_count = 0;
static volatile int ap_boot_success = 0;

/* AP entry function called from trampoline */
void ap_entry(void)
{
    ap_bootstrap(1);
}

static void copy_trampoline(void)
{
    uint64_t dest = AP_TRAMPOLINE_BASE;
    uint64_t src = (uint64_t)(uintptr_t)_binary_build_arch_x86_64_ap_trampoline_bin_start;
    size_t size = (uintptr_t)_binary_build_arch_x86_64_ap_trampoline_bin_end - 
                  (uintptr_t)_binary_build_arch_x86_64_ap_trampoline_bin_start;
    
    serial_print("[smp] copying trampoline to 0x");
    serial_print_hex(dest);
    serial_print(" (");
    serial_print_dec(size);
    serial_print(" bytes)\n");
    
    /* Copy trampoline code */
    for (size_t i = 0; i < size && i < 4096; i++) {
        *(uint8_t *)(uintptr_t)(dest + i) = *(uint8_t *)(uintptr_t)(src + i);
    }
    
    /* Set PML4 address in trampoline (offset 0x40) */
    *(uint64_t *)(uintptr_t)(dest + 0x40) = kernel_pml4_phys;
    
    /* Set entry point pointer (offset 0x60) */
    *(uint64_t *)(uintptr_t)(dest + 0x60) = (uint64_t)(uintptr_t)ap_entry;
}

int smp_is_bsp(void)
{
    uint64_t msr = read_msr(MSR_APIC_BASE);
    return (msr & MSR_APIC_BASE_BSP) != 0;
}

uint32_t smp_current_apic_id(void)
{
    return lapic_get_id();
}

int smp_current_cpu(void)
{
    struct cpu_info *cpu = cpu_current();
    if (!cpu) return -1;
    return (int)(cpu - cpus);
}

int smp_cpu_count(void)
{
    int count = 0;
    for (int i = 0; i < MAX_CPUS; i++) {
        if (cpus[i].flags & CPU_FLAG_PRESENT && cpus[i].state == CPU_STATE_ONLINE) {
            count++;
        }
    }
    return count;
}

int smp_enabled(void)
{
    return smp_config.enabled;
}

static void smp_boot_fallback(void)
{
    serial_print("[smp] fallback: trying to boot AP at APIC ID 1\n");
    
    /* Try to boot AP at APIC ID 1 */
    lapic_send_init_ipi(1);
    timer_sleep_ms(10);
    
    uint8_t vector = AP_TRAMPOLINE_BASE / 4096;
    lapic_send_startup_ipi(1, vector);
    timer_sleep_ms(10);
    lapic_send_startup_ipi(1, vector);
    timer_sleep_ms(100);
    
    /* Check if CPU 1 booted */
    if (smp_cpu_count() > 1) {
        serial_print("[smp] fallback: AP at APIC ID 1 booted successfully\n");
    } else {
        serial_print("[smp] fallback: AP at APIC ID 1 did not boot\n");
    }
}

void smp_init(void)
{
    serial_print("[smp] initializing...\n");
    
    if (!smp_config.enabled) {
        serial_print("[smp] disabled by config\n");
        return;
    }
    
    ap_boot_phase = SMP_PHASE_ACPI;
    
    /* Initialize ACPI to find MADT */
    acpi_init();
    
    ap_boot_phase = SMP_PHASE_APIC;
    
    /* Initialize Local APIC for BSP */
    lapic_init();
    
    /* Initialize CPU data */
    cpu_init();
    
    /* Initialize I/O APIC */
    if (smp_config.use_ioapic) {
        ioapic_init();
    }
    
    /* Initialize IPI system */
    ipi_init();
    
    ap_boot_phase = SMP_PHASE_BOOT;
    
    /* Copy AP trampoline to low memory */
    copy_trampoline();
    
    /* Boot APs */
    smp_boot_aps();
    
    /* Wait for APs to boot */
    smp_wait_for_aps(1000);
    
    ap_boot_phase = SMP_PHASE_RUNNING;
    
    serial_print("[smp] initialization complete, ");
    serial_print_dec(smp_cpu_count());
    serial_print(" CPUs online\n");
}

void smp_boot_aps(void)
{
    serial_print("[smp] booting APs...\n");
    
    /* Get CPU info from MADT */
    struct madt_info *madt = madt_get_info();
    if (!madt) {
        serial_print("[smp] WARNING: no MADT, using fallback\n");
        smp_boot_fallback();
        return;
    }
    
    ap_booted_count = 0;
    ap_boot_success = 0;
    
    /* Boot each AP */
    for (uint32_t i = 0; i < madt->lapic_count; i++) {
        struct madt_lapic *lapic = &madt->lapics[i];
        
        /* Skip BSP (processor 0) */
        if (i == 0) continue;
        
        /* Skip if not enabled */
        if (!(lapic->flags & 1)) continue;
        
        /* Check if we have room */
        if (smp_cpu_count() >= MAX_CPUS) {
            serial_print("[smp] WARNING: too many CPUs, stopping\n");
            break;
        }
        
        serial_print("[smp] booting APIC ID ");
        serial_print_dec(lapic->apic_id);
        serial_print(" (processor ");
        serial_print_dec(lapic->processor_id);
        serial_print(")\n");
        
        /* Send INIT IPI */
        lapic_send_init_ipi(lapic->apic_id);
        
        /* Send SIPI with trampoline vector */
        uint8_t vector = AP_TRAMPOLINE_BASE / 4096;
        lapic_send_startup_ipi(lapic->apic_id, vector);
        
        /* Wait a bit */
        timer_sleep_ms(10);
        
        /* Send second SIPI (recommended) */
        lapic_send_startup_ipi(lapic->apic_id, vector);
        
        timer_sleep_ms(10);
        
        ap_booted_count++;
    }
    
    serial_print("[smp] sent SIPI to ");
    serial_print_dec(ap_booted_count);
    serial_print(" APs\n");
}

void smp_wait_for_aps(int timeout_ms)
{
    int elapsed = 0;
    int target = ap_booted_count;
    
    if (target == 0) {
        serial_print("[smp] no APs to wait for\n");
        return;
    }
    
    serial_print("[smp] waiting for APs to come online...\n");
    
    while (elapsed < timeout_ms) {
        int online = smp_cpu_count() - 1;
        if (online >= target) {
            ap_boot_success = 1;
            serial_print("[smp] all ");
            serial_print_dec(online);
            serial_print(" APs online\n");
            return;
        }
        timer_sleep_ms(10);
        elapsed += 10;
    }
    
    serial_print("[smp] WARNING: timeout waiting for APs (");
    serial_print_dec(smp_cpu_count() - 1);
    serial_print("/");
    serial_print_dec(target);
    serial_print(" online)\n");
}

void ap_bootstrap(uint32_t cpu_index)
{
    serial_print("[smp] AP bootstrap: CPU ");
    serial_print_dec(cpu_index);
    serial_print("\n");
    
    lapic_init();
    cpu_ap_init(lapic_get_id(), cpu_index);
    lapic_ap_boot_report();
    
    __asm__ volatile ("sti");
    
    serial_print("[smp] AP ");
    serial_print_dec(cpu_index);
    serial_print(" (APIC ID ");
    serial_print_dec(lapic_get_id());
    serial_print(") running\n");
    
    for (;;) {
        __asm__ volatile ("hlt");
    }
}