static int test_random_basic(void)
{
    uint8_t a[32], b[32];

    serial_print("[selftest] CSPRNG basic\n");

    random_bytes(a, sizeof(a));
    random_bytes(b, sizeof(b));

    if (memcmp(a, b, sizeof(a)) == 0) {
        serial_print("  [FAIL] two consecutive random_bytes() returned same\n");
        return -1;
    }


    uint8_t acc = 0;
    for (size_t i = 0; i < sizeof(a); i++) acc |= a[i];
    if (acc == 0) {
        serial_print("  [FAIL] random_bytes() returned all zeros\n");
        return -1;
    }

    serial_print("  [PASS] CSPRNG produces unique non-zero output\n");
    return 0;
}

