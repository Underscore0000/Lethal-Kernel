static int test_aead_tampered_tag(void)
{
    uint8_t key[32];
    uint8_t nonce[12] = {0};
    uint8_t aad[4] = {1,2,3,4};
    uint8_t pt[16] = "hello world!!!!!";
    uint8_t ct[16];
    uint8_t tag[16];
    uint8_t out[16];

    serial_print("[selftest] AEAD tampered-tag rejection\n");

    for (int i = 0; i < 32; i++) key[i] = (uint8_t)i;

    chacha20poly1305_encrypt(ct, tag, pt, 16, aad, 4, nonce, key);
    tag[0] ^= 0x01;

    if (chacha20poly1305_decrypt(out, ct, 16, aad, 4, tag, nonce, key) == 0) {
        serial_print("  [FAIL] tampered tag accepted!\n");
        return -1;
    }
    serial_print("  [PASS] tampered tag rejected\n");
    return 0;
}



static int test_x25519_roundtrip(void)
{
    uint8_t in[32], out[32];

    for (int i = 0; i < 32; i++) in[i] = (uint8_t)(i * 7 + 3);
    in[31] = 0x03;  


    curve25519_scalarmult(out, in, in); 
    (void)out;


    serial_print("[selftest] curve25519 sanity (non-zero)\n");


    uint8_t sk[32];
    uint8_t pk[32];
    for (int i = 0; i < 32; i++) sk[i] = (uint8_t)(i + 1);

    curve25519_public_key(pk, sk);
    uint8_t acc = 0;
    for (int i = 0; i < 32; i++) acc |= pk[i];

    if (acc == 0) {
        serial_print("  [FAIL] X25519(sk, 9) returned all zeros\n");
        return -1;
    }
    serial_print("  [PASS] X25519(sk, 9) non-zero\n");
    return 0;
}



