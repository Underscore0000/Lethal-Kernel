/* --------------------------------------------------------------------------
 * Utility: hex dump e confronto
 * -------------------------------------------------------------------------- */

static void print_hex(const char *label, const uint8_t *data, size_t len)
{
    serial_print(label);
    for (size_t i = 0; i < len; i++) {
        serial_print_hex8(data[i]);
    }
    serial_print("\n");
}

static int expect_bytes(const char *label,
                        const uint8_t *got,
                        const uint8_t *want,
                        size_t len)
{
    if (memcmp(got, want, len) == 0) {
        serial_print("  [PASS] ");
        serial_print(label);
        serial_print("\n");
        return 0;
    }
    serial_print("  [FAIL] ");
    serial_print(label);
    serial_print("\n");
    print_hex("    got : ", got, len);
    print_hex("    want: ", want, len);
    return -1;
}

